// Writes assets/art-data.js: the painted tile faces and backs as data: URIs, for file:// play only.
//
// Under file:// every image file counts as cross-origin, so drawing one into the face atlas taints the canvas,
// and WebGL refuses to upload a tainted canvas as a texture. Images decoded from data: URIs don't taint.
// Over http the game loads assets/*.webp as usual and never requests this file.
//
//   node games/mahjong/tools/build-art-data.mjs        (run after art-pack.mjs)
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const DIR = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'assets');
const manifest = JSON.parse(fs.readFileSync(path.join(DIR, 'manifest.json'), 'utf8'));
// everything the face atlas draws: faces, pips, fish and tile backs (not tables, backdrops or the title)
const want = Object.keys(manifest).filter((n) => !/^(table-|title-|backdrop-|slab-)/.test(n));
const out = {};
let bytes = 0;
for (const n of want) {
  const buf = fs.readFileSync(path.join(DIR, manifest[n].file));
  out[n] = 'data:image/webp;base64,' + buf.toString('base64');
  bytes += buf.length;
}
const js = '/* Generated by tools/build-art-data.mjs from assets/*.webp: tile art as data: URIs, loaded only under file://. */\n'
  + 'window.MJ_ART_DATA=' + JSON.stringify(out) + ';\n';
fs.writeFileSync(path.join(DIR, 'art-data.js'), js);
console.log('assets/art-data.js:', want.length, 'images,', (bytes / 1024).toFixed(0), 'KB of WebP ->', (js.length / 1024).toFixed(0), 'KB');
